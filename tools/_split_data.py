#!/usr/bin/env python3
"""Split the big monolithic data files into a tiny index + per-test chunks.

Reads the compiler outputs (assets/data/hoeren-tests.js, lesen-tests.js) and
emits file://-friendly <script src> chunks (no fetch, no JSON):
  - assets/data/hoeren-index.js          (~6 KB, [{name, id, file}])
  - assets/data/hoeren/<id>.js  x100    (~16 KB each)
  - assets/data/lesen-t1.js .. lesen-t4.js (one per Teil)
Run: python3 tools/_split_data.py
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / 'assets' / 'data'


def slug(s):
    """Port of Progress.slug (assets/progress.js) — stable ids."""
    s = str(s or '').lower()
    for a, b in [('ä', 'ae'), ('ö', 'oe'), ('ü', 'ue'), ('ß', 'ss')]:
        s = s.replace(a, b)
    s = re.sub(r'[^a-z0-9]+', '-', s).strip('-')
    return s[:80]


def load_global(path, name):
    """Extract `window.NAME = [...]` array from a generated data file."""
    src = Path(path).read_text(encoding='utf-8')
    m = re.search(r'window\.' + re.escape(name) + r'\s*=\s*(\[.*?\n\]);',
                  src, re.S)
    if not m:
        sys.exit(f'global {name} not found in {path}')
    return json.loads(m.group(1))


def main():
    # ---------- HOEREN ----------
    tests = load_global(DATA / 'hoeren-tests.js', 'HOEREN_TESTS')
    chunk_dir = DATA / 'hoeren'
    chunk_dir.mkdir(parents=True, exist_ok=True)
    index = []
    for i, t in enumerate(tests):
        tid = t.get('id') or ('test:' + slug(t.get('name')))
        t['id'] = tid
        fname = slug(tid) + '.js'
        index.append({'name': t.get('name'), 'id': tid, 'file': fname})
        body = json.dumps(t, ensure_ascii=False, separators=(',', ':'))
        (chunk_dir / fname).write_text(
            f'// Auto-generated by tools/_split_data.py — DO NOT edit by hand.\n'
            f'window.HOEREN_TESTS = window.HOEREN_TESTS || [];\n'
            f'window.HOEREN_TESTS[{i}] = {body};\n', encoding='utf-8')
    (DATA / 'hoeren-index.js').write_text(
        '// Auto-generated by tools/_split_data.py — DO NOT edit by hand.\n'
        f'window.HOEREN_INDEX = {json.dumps(index, ensure_ascii=False, indent=1)};\n',
        encoding='utf-8')
    # round-trip check
    rt = json.loads((DATA / 'hoeren-index.js').read_text(encoding='utf-8')
                    .split('window.HOEREN_INDEX = ', 1)[1].rstrip().rstrip(';'))
    assert [e['id'] for e in rt] == [t['id'] for t in tests], 'index mismatch'
    print(f'hoeren: index {len(index)} tests, '
          f'{(DATA / "hoeren-index.js").stat().st_size // 1024} KB')

    # ---------- LESEN (one file per Teil, same globals) ----------
    for n in '1234':
        g = f'LESEN_T{n}_SETS'
        sets = load_global(DATA / 'lesen-tests.js', g)
        body = json.dumps(sets, ensure_ascii=False, separators=(',', ':'))
        out = DATA / f'lesen-t{n}.js'
        payload = f'window.{g} = {body};\n'
        out.write_text(
            f'// Auto-generated by tools/_split_data.py — DO NOT edit by hand.\n'
            f'// Split of lesen-tests.js ({g}), loaded lazily per Teil.\n'
            + payload, encoding='utf-8')
        rt = json.loads(payload.split(' = ', 1)[1].rstrip().rstrip(';'))
        assert len(rt) == len(sets), f'{g} mismatch'
        print(f'{g}: {len(sets)} sets, {out.stat().st_size // 1024} KB')


if __name__ == '__main__':
    main()
