#!/usr/bin/env python3
"""Compile all _testN_data.json files into assets/data/hoeren-tests.js.

The test data lives in a SEPARATE JS file (assigned to window.HOEREN_TESTS) and
is pulled into hoeren.html via <script src>. This keeps the HTML small and the
data/presentation separated, while still working offline under file:// — a
.json + fetch() would be blocked by the browser's file:// CORS policy, but a
<script src> is not.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOOLS = ROOT / 'tools'
OUT = ROOT / 'assets' / 'data' / 'hoeren-tests.js'

# Load all _testN_data.json files in numerical order
test_files = sorted(TOOLS.glob('_test*_data.json'),
                    key=lambda p: int(re.search(r'_test(\d+)_data', p.name).group(1)))
tests = [json.loads(f.read_text(encoding='utf-8')) for f in test_files]

print(f'Loaded {len(tests)} tests:')
for t in tests:
    print(f'  {t["id"]}: {t["name"]}')

# Serialize as a JS array literal with 2-space base indent
body = ',\n'.join(
    '\n'.join('  ' + line for line in json.dumps(t, ensure_ascii=False, indent=2).split('\n'))
    for t in tests
)

OUT.parent.mkdir(parents=True, exist_ok=True)
header = (
    '// Auto-generated by tools/_compile_tests.py — DO NOT edit by hand.\n'
    '// Source of truth: tools/_testN_data.json.\n'
    '// Loaded via <script src> so it works under file:// (offline);\n'
    '// a .json + fetch() would be blocked by the file:// CORS policy.\n'
)
OUT.write_text(f'{header}window.HOEREN_TESTS = [\n{body}\n];\n', encoding='utf-8')

print(f'\nWrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size // 1024} KB, {len(tests)} tests)')
